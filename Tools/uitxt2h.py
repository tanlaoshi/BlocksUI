#!/usr/bin/env python3
"""uitxt2h — .uitxt → C header (Bingo 约定，运行时零解析)."""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

KIND_MAP = {
    "label": "UI_WIDGET_LABEL",
    "button": "UI_WIDGET_BUTTON",
    "checkbox": "UI_WIDGET_CHECKBOX",
    "textbox": "UI_WIDGET_TEXTBOX",
}


def parse_uitxt(text: str):
    lines = []
    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        lines.append(line)
    if not lines or not lines[0].startswith("window "):
        raise SystemExit("error: first effective line must be window \"title\" w h")
    m = re.match(r'window\s+"([^"]*)"\s+(\d+)\s+(\d+)\s*$', lines[0])
    if not m:
        raise SystemExit("error: bad window line")
    title, width, height = m.group(1), int(m.group(2)), int(m.group(3))
    widgets = []
    seen = set()
    for line in lines[1:]:
        parts = line.split()
        if not parts:
            continue
        kind = parts[0].lower()
        if kind not in KIND_MAP:
            raise SystemExit(f"error: unknown type {kind}")
        fields = {"id": None, "x": None, "y": None, "w": None, "h": None, "text": ""}
        rest = line[len(parts[0]) :].strip()
        for token in re.findall(r'(\w+)=("(?:\\.|[^"])*"|[^\s]+)', rest):
            key, val = token
            if val.startswith('"') and val.endswith('"'):
                val = bytes(val[1:-1], "utf-8").decode("unicode_escape")
            fields[key] = val
        for need in ("id", "x", "y", "w", "h"):
            if fields[need] is None:
                raise SystemExit(f"error: missing {need} in: {line}")
        wid = fields["id"]
        if wid in seen:
            raise SystemExit(f"error: duplicate id {wid}")
        seen.add(wid)
        widgets.append(
            {
                "kind": kind,
                "id": wid,
                "x": int(fields["x"]),
                "y": int(fields["y"]),
                "w": int(fields["w"]),
                "h": int(fields["h"]),
                "text": fields.get("text") or "",
            }
        )
    return title, width, height, widgets


def id_enum(name: str) -> str:
    return "ID_" + re.sub(r"[^A-Za-z0-9]", "_", name).upper()


def emit(path: Path, title: str, width: int, height: int, widgets: list) -> str:
    guard = re.sub(r"[^A-Za-z0-9]", "_", path.stem).upper() + "_UI_H"
    out = []
    out.append(f"#ifndef {guard}")
    out.append(f"#define {guard}")
    out.append("")
    out.append("/* generated by BlocksUI Tools/uitxt2h.py — do not edit */")
    out.append("")
    out.append("#ifndef UI_WIDGET_LABEL")
    out.append("#define UI_WIDGET_LABEL   0")
    out.append("#define UI_WIDGET_BUTTON  1")
    out.append("#define UI_WIDGET_CHECKBOX 2")
    out.append("#define UI_WIDGET_TEXTBOX 3")
    out.append("typedef struct {")
    out.append("    int Kind;")
    out.append("    int X, Y, W, H;")
    out.append("    const char *Id;")
    out.append("    const char *Text;")
    out.append("} UI_WIDGET;")
    out.append("#endif")
    out.append("")
    out.append(f'#define MYAPP_WIN_TITLE "{title}"')
    out.append(f"#define MYAPP_WIN_W {width}")
    out.append(f"#define MYAPP_WIN_H {height}")
    out.append("")
    out.append("enum {")
    for i, w in enumerate(widgets):
        comma = "," if i + 1 < len(widgets) else ""
        out.append(f"    {id_enum(w['id'])} = {i}{comma}")
    out.append("};")
    out.append("")
    out.append("static const UI_WIDGET gMyAppWidgets[] = {")
    for w in widgets:
        text = w["text"].replace("\\", "\\\\").replace('"', '\\"')
        out.append(
            f'    {{ {KIND_MAP[w["kind"]]}, {w["x"]}, {w["y"]}, {w["w"]}, {w["h"]}, '
            f'"{w["id"]}", "{text}" }},'
        )
    out.append("};")
    out.append(f"#define MYAPP_WIDGET_COUNT {len(widgets)}")
    out.append("")
    out.append(f"#endif /* {guard} */")
    out.append("")
    return "\n".join(out)


def main() -> None:
    ap = argparse.ArgumentParser(description="Convert .uitxt to C header")
    ap.add_argument("uitxt", type=Path)
    args = ap.parse_args()
    text = args.uitxt.read_text(encoding="utf-8")
    title, width, height, widgets = parse_uitxt(text)
    sys.stdout.write(emit(args.uitxt, title, width, height, widgets))


if __name__ == "__main__":
    main()
