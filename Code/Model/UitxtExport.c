/*
 * UitxtExport.c — 写出 Bingo 约定 .uitxt
 */
#include "UitxtExport.h"

#include <stdio.h>

static void BlocksUIUitxtEscapeText(FILE *File, const char *Text) {
    const char *P;

    fputc('"', File);
    if (Text == 0) {
        fputc('"', File);
        return;
    }
    for (P = Text; *P; P++) {
        if (*P == '"' || *P == '\\') {
            fputc('\\', File);
        }
        fputc(*P, File);
    }
    fputc('"', File);
}

int BlocksUIUitxtExportPath(const BlocksUIDocument *Document, const char *Path) {
    FILE *File;
    int i;

    if (Document == 0 || Path == 0 || Path[0] == 0) {
        return -1;
    }
    File = fopen(Path, "w");
    if (File == 0) {
        return -1;
    }
    fprintf(File, "# generated by BlocksUI\n");
    fprintf(File, "window \"%s\" %d %d\n", Document->Title, Document->Width,
            Document->Height);
    for (i = 0; i < Document->Count; i++) {
        const BlocksUIWidget *Widget = &Document->Widgets[i];

        fprintf(File, "%s id=%s x=%d y=%d w=%d h=%d text=",
                BlocksUIWidgetKindName(Widget->Kind), Widget->Id, Widget->X,
                Widget->Y, Widget->Width, Widget->Height);
        BlocksUIUitxtEscapeText(File, Widget->Text);
        fputc('\n', File);
    }
    fclose(File);
    return 0;
}
